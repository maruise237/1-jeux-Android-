// End-to-end check of stats + announcement against a running server (server/dev-server.mjs or Vercel).
// Usage: CHROMIUM_PATH=... API=http://localhost:3999 node tools/test-online.mjs [screenshotDir]
import { chromium } from 'playwright-core';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const API = process.env.API || 'http://localhost:3999';
const out = process.argv[2];
const root = path.resolve('www');
const server = http.createServer((req, res) => { const f = path.join(root, req.url.split('?')[0]); if (!f.startsWith(root) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'content-type': f.endsWith('.js') ? 'text/javascript' : f.endsWith('.css') ? 'text/css' : 'text/html' }); fs.createReadStream(f).pipe(res); });
await new Promise(r => server.listen(0, r));
const b = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const p = await b.newPage({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2 });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.route('**/js/online-config.js', r => r.fulfill({ contentType: 'text/javascript', body: `window.SHADOW_ONLINE={api:${JSON.stringify(API)},version:'test'}` }));
let opened = null; p.context().on('page', np => { opened = np.url(); });
const check = (name, ok) => { console.log((ok ? 'OK   ' : 'FAIL ') + name); if (!ok) process.exitCode = 1; };
await p.goto(`http://localhost:${server.address().port}/index.html`); await p.waitForTimeout(800);
check('no announcement at launch', !(await p.isVisible('#promo')));
await p.click('#btn-play'); await p.waitForTimeout(300);
await p.evaluate(() => { const S = window.__shadowStrike; for (const g of S.guards) if (g.alive) S.kill(g); S.tick(240); });
await p.waitForTimeout(1500);
await p.click('#btn-result-menu'); await p.waitForTimeout(1200);
check('announcement after a level (needs one active promo)', await p.isVisible('#promo'));
if (out) await p.screenshot({ path: out + '/promo.png' });
await p.click('#btn-promo-go'); await p.waitForTimeout(800);
check('link opened in a new window', !!opened);
check('game page still here', await p.evaluate(() => !!window.KamOnline));
await p.evaluate(() => window.KamOnline.flush()); await p.waitForTimeout(800);
check('queue sent', (await p.evaluate(() => window.KamOnline.queued)) === 0);
await p.click('#btn-play'); await p.waitForTimeout(200); await p.keyboard.press('Escape'); await p.click('#btn-quit'); await p.waitForTimeout(1000);
check('at most one announcement per session', !(await p.isVisible('#promo')));
await p.context().setOffline(true);
await p.click('#btn-play'); await p.waitForTimeout(200);
await p.evaluate(() => window.KamOnline.flush()); await p.waitForTimeout(300);
check('offline: events kept on the phone', (await p.evaluate(() => window.KamOnline.queued)) > 0);
await p.context().setOffline(false);
await p.evaluate(() => window.KamOnline.flush()); await p.waitForTimeout(1000);
check('back online: queue sent', (await p.evaluate(() => window.KamOnline.queued)) === 0);
check('no page errors', !errs.length); if (errs.length) console.log(errs);
await b.close(); server.close();
